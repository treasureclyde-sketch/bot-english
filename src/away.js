// Автоответ в бизнес-чатах ОТ ЛИЦА владельца (Telegram Business).
// Отвечает как сам владелец, с жёсткими рамками: никакой политики и тем,
// за которые можно огрести. Приватные заметки/задачи сюда НЕ подмешиваем —
// ответы уходят чужим людям, лишний контекст = риск утечки.

import * as db from "./db.js";
import { anthropicMessages, extractText } from "./llm.js";

// Стабильная (кэшируемая) инструкция-персона.
const AWAY_SYSTEM =
  "Ты ведёшь личную переписку в Telegram ПОЛНОСТЬЮ от лица владельца аккаунта — " +
  "будто это он сам. Пиши от первого лица, по-русски, коротко и по-разговорному, " +
  "как в мессенджере (можно без заглавных и формальностей). НЕ раскрывай, что ты " +
  "бот или ИИ.\n\n" +
  "ЖЁСТКИЕ ЗАПРЕТЫ (ответы уходят под именем владельца реальным людям):\n" +
  "- Никакой политики, власти, выборов, войн, религии, национальных и прочих " +
  "острых общественных тем. На такое не отвечай по сути — мягко уходи: " +
  "«о, давай не в переписке», «потом обсудим вживую».\n" +
  "- Ничего, за что можно огрести: оскорбления, угрозы, что-либо незаконное, " +
  "интим/18+, деньги и переводы, обещания и договорённости за владельца (встречи, " +
  "сделки, долги), выдача личных данных (адрес, документы, пароли).\n" +
  "- Скользкая тема или сомневаешься — не отвечай по сути: отшутись, переведи " +
  "тему или напиши «отвечу чуть позже».\n" +
  "- Не подтверждай встречи и обязательства за владельца и не строй планов.\n\n" +
  "Если сообщение не требует ответа (реакция, стикер, «ок», «ахах», «+») — верни " +
  "РОВНО [skip] и ничего больше.\n" +
  "Отвечай одним коротким сообщением, без кавычек и подписи.";

// Сгенерировать ответ или null (если отвечать не нужно / скользко).
export async function awayReply(env, ownerId, chatId) {
  const hist = await db.recentBizMessages(env, ownerId, chatId, 10);
  const messages = hist.map((m) => ({
    role: m.role === "them" ? "user" : "assistant",
    content: m.content,
  }));
  while (messages.length && messages[0].role === "assistant") messages.shift();
  if (!messages.length || messages[messages.length - 1].role !== "user") return null;

  const system = [{ type: "text", text: AWAY_SYSTEM, cache_control: { type: "ephemeral" } }];
  const resp = await anthropicMessages(env, { system, messages });
  const text = extractText(resp.content).trim();
  if (!text) return null;
  if (/^\[skip\]$/i.test(text)) return null;
  return text;
}
